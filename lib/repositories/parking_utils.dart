//funções de geração

ParkingLayout _parkingLayout() {
  return ParkingLayout(
    width: 1000.0,
    height: 1000.0,
    elements: generateLayoutElements(),
    spots: _generateSpots(),
  );
}

Map<String, Spot> _generateSpots() {
  final random = Random();
  final types = ['carro', 'moto', 'deficiente'];

  return Map.fromEntries(
    List.generate(3, (i) {
      final id = 'A${i + 1}';
      final spot = Spot(
        id: id,
        status: random.nextBool(),
        type: types[random.nextInt(types.length)],
        x: 100.0 + (i * 50),
        y: 100.0,
        width: 50,
        height: 80,
        rotation: null,
      );
      return MapEntry(id, spot);
    }),
  );
}

Map<String, LayoutElement> generateLayoutElements() {
  return {
