Future<void> updateMultipleArrows() async {
  final repository = ParkingRepository();

  Map<String, dynamic> updates = {};

  //quantidade de elementos a ser criado
  int elementsNumber = 5;

  //numero da primeira seta q vai alterar, vai incrementar de 1 em 1 dai
  int nameCount = 1;

  for (int i = 0; i < elementsNumber; i++) {
    //colocar i * no x caso esteja tratando de colunas no y é quando tem linhas
    final double x = 485.0; //+ (i * 275);
    final double y = 75.0 + (i * 225);
    final String name = 'arrow$nameCount';
    final element = LayoutElement(type: 'arrow', x: x, y: y, rotation: 0);
    updates['floors.0.layout.elements.$name'] = element.toMap();
    nameCount++;
  }

  await repository.updateParking('1', updates);
}

