//atualização de vagas (posição e dados)

Future<void> updateSpots() async {
  final repository = ParkingRepository();
  final random = Random();
  //final types = ['carro', 'moto', 'deficiente'];

  Map<String, dynamic> updates = {};

  const int spotsPerRow = 16;
  const List<String> prefixes = ['I', 'J'];
  //row pode funcionar como column, é apenas um nome genérico
  for (int row = 0; row < prefixes.length; row++) {
    final prefix = prefixes[row];
    for (int i = 0; i < spotsPerRow; i++) {
      final int spotNumber = i + 1;
      final String spotId = '$prefix$spotNumber';
      final double x = 100.0 + (i * 50);
      //se quiser q os spots saiam em coluna colocar i no y, senão coloque no x
      final double y = 900.0 + (row * 150);
      final spot = Spot(
        id: spotId,
        status: random.nextBool(),
        type: 'carro',
        x: x,
        y: y,
        width: 50.0,
        height: 75.0,
      );
      //criando uma lista de map String dynamic e add todos de uma vez, pega o cahve q é o colchetes e bota como valor o spot.toMap
      updates['floors.0.layout.spots.$spotId'] = spot.toMap();
    }
  }

  await repository.updateParking('1', updates);
}

